#!/usr/bin/env node
import fs from 'node:fs';
const fail=m=>{console.error('VERIFY_MOBILE_R1 FAIL:',m);process.exit(1)};
const read=p=>{try{return fs.readFileSync(p,'utf8')}catch{fail('missing '+p)}};
const i=read('index.html'),p=JSON.parse(read('assets/job-title-progression.json')),sw=read('service-worker.js'),m=JSON.parse(read('manifest.webmanifest')),v=read('VERSION.txt').trim();
const E='MOBILE-R1.5.75-R1574-STARTUP-HOTFIX-VISUAL-FOCUS';
const tag='<style id="r1574-career-visual-focus-style">', body='<body class="subview-list">';
if(v!==E)fail('VERSION mismatch');
if(!i.includes('<meta name="app-release" content="'+E+'">'))fail('release meta mismatch');
if(!i.includes('R1575_R1574_STARTUP_HOTFIX_RELEASE'))fail('R1.5.75 hotfix marker missing');
if((i.match(/id="r1574-career-visual-focus-style"/g)||[]).length!==1)fail('R1.5.74 style block count mismatch');
const s=i.indexOf(tag),b=i.indexOf(body),h=i.lastIndexOf('</head>',b);
if(!(s>0&&s<h&&h<b))fail('R1.5.74 CSS is not located inside the real application head');
if(!i.includes('بداية التغطية')||!i.includes('نهاية التغطية'))fail('coverage infographic labels missing');
const reportWrite=i.indexOf('w.document.open();w.document.write(doc);');
const reportVar=i.lastIndexOf("var doc='",reportWrite);
if(reportVar<0||reportWrite<0)fail('report document structure missing');
const reportRegion=i.slice(reportVar,reportWrite);
if(reportRegion.includes('r1574-career-visual-focus-style'))fail('R1.5.74 CSS remains inside report JavaScript region');
if(!reportRegion.includes("</body></html>';"))fail('report document closing sequence not restored');
if(!p.startupHotfixR1575||p.startupHotfixR1575.structuralVerification!==true||p.startupHotfixR1575.careerLogicChanged!==false)fail('hotfix metadata missing');
if(p.chains.length!==189||p.validatedStepCount!==925||p.coverage.mappedTitles!==925||p.coverage.unmappedTitles!==391||Number(p.coverage.exactCoveragePercent)!==70.3)fail('Career map changed');
if(!i.includes("service-worker.js?v=1575")||!i.includes("employee-registry-ui-r1575")||!i.includes("APP_RELEASE||'r1575'"))fail('index release/cache references not fully bumped');
if(!sw.includes('MOBILE-R1.5.75-SERVICE-WORKER-NO-STALE-UI')||!sw.includes('__offline_index_r1575__'))fail('service worker mismatch');
if(!String(m.name).includes('R1.5.75'))fail('manifest mismatch');
console.log('VERIFY_MOBILE_R1 OK:',E);
console.log('VERIFY_STARTUP_HOTFIX OK: misplaced R1.5.74 CSS removed from report JavaScript region');
console.log('VERIFY_STARTUP_STRUCTURE OK: visual CSS is in the real application head and report document closing sequence is restored');
console.log('VERIFY_VISUAL_FOCUS OK: R1.5.74 design retained including coverage start/end infographic and directory styling');
console.log('VERIFY_CAREER_MAP OK: 189 chains / 925 mapped / 391 audit queue / 70.3% unchanged');
console.log('VERIFY_REGRESSION OK: reference center, exact matching, current anchors, and navigation remain retained');
